/// The key that types V, under ⌘ or plain, on the current layout. Call it on the
/// main thread, where Text Input Sources may be entered, for each paste: the layout
/// can change between pastes (QWERTY to Dvorak moves V).
pub fn v_key() -> Option<u16> {
    layout_key_code('v')
}

fn layout_key_code(character: char) -> Option<u16> {
    let find = |source: InputSourceRef| -> Option<u16> {
        // SAFETY: a retained source; the property is CFData holding a UCKeyboardLayout.
        let data = unsafe { TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) };
        if data.is_null() {
            return None;
        }
        // SAFETY: as above.
        let layout = unsafe { CFDataGetBytePtr(data) };
        let codes: HashMap<u32, u16> = [COMMAND_MODIFIER_STATE, NO_MODIFIER_STATE]
            .into_iter()
            .filter_map(|state| {
                (0..128)
                    .find(|&code| {
                        translate(layout, code, state)
                            .is_some_and(|t| t.eq_ignore_ascii_case(&character.to_string()))
                    })
                    .map(|code| (state, code))
            })
            .collect();
        codes
            .get(&COMMAND_MODIFIER_STATE)
            .or_else(|| codes.get(&NO_MODIFIER_STATE))
            .copied()
    };
    // Non-Latin layouts type no V; AppKit resolves ⌘V on the ASCII-capable one.
    // SAFETY: TIS copy functions return retained sources, released here.
    [
        unsafe { TISCopyCurrentKeyboardLayoutInputSource() },
        unsafe { TISCopyCurrentASCIICapableKeyboardLayoutInputSource() },
    ]
    .into_iter()
    .filter(|source| !source.is_null())
    .map(|source| {
        let code = find(source);
        // SAFETY: we own the retained source.
        unsafe { CFRelease(source) };
        code
    })
    .collect::<Vec<_>>()
    .into_iter()
    .flatten()
    .next()
}

fn translate(layout: *const u8, key_code: u16, modifier_state: u32) -> Option<String> {
    let mut dead_key_state = 0;
    let mut output = [0u16; 4];
    let mut length = 0;
    // SAFETY: `layout` points into retained layout data; the buffers are valid.
    let status = unsafe {
        UCKeyTranslate(
            layout,
            key_code,
            KEY_ACTION_DISPLAY,
            modifier_state,
            LMGetKbdType().into(),
            NO_DEAD_KEYS,
            &mut dead_key_state,
            output.len() as isize,
            &mut length,
            output.as_mut_ptr(),
        )
    };
    (status == 0 && length > 0)
        .then(|| String::from_utf16(&output[..length as usize]).ok())
        .flatten()
}

/// The modifier presses, the key, and the releases in reverse.
fn shortcut(key_code: u16, modifiers: &[(u64, u16)]) -> Vec<(u16, bool, u64)> {
    let all = modifiers.iter().fold(0, |flags, (flag, _)| flags | flag);
    let mut events = vec![];
    let mut held = 0;
    for (flag, key) in modifiers {
        held |= flag;
        events.push((*key, true, held));
    }
    events.extend([(key_code, true, all), (key_code, false, all)]);
    for (flag, key) in modifiers.iter().rev() {
        held &= !flag;
        events.push((*key, false, held));
    }
    events
}

fn post(specs: &[(u16, bool, u64)]) -> Result<()> {
    let events = specs
        .iter()
        .map(|&spec| KeyboardEvent::new(spec))
        .collect::<Result<Vec<_>>>()?;
    for event in &events {
        event.post();
    }
    Ok(())
}

/// Types `text` as key events, never touching the clipboard. A line break is
/// ⇧↩, so a chat box adds a line instead of sending.
fn type_text(text: &str) -> Result<()> {
    let mut events = vec![];
    for stroke in strokes(text) {
        match stroke {
            Stroke::Text(units) => {
                for down in [true, false] {
                    let event = KeyboardEvent::new((0, down, 0))?;
                    event.set_text(&units);
                    events.push(event);
                }
            }
            Stroke::LineBreak => {
                for spec in shortcut(RETURN_KEY_CODE, &[(SHIFT_FLAG, SHIFT_KEY_CODE)]) {
                    events.push(KeyboardEvent::new(spec)?);
                }
            }
        }
    }
    for event in &events {
        event.post();
    }
    Ok(())
}

#[derive(Debug, PartialEq, Eq)]
enum Stroke {
    Text(Vec<u16>),
    LineBreak,
}

/// Splits text into events of at most [`MAX_UNICODE_UNITS`] UTF-16 units without
/// splitting a surrogate pair. `\r\n`, `\n` and `\r` are each one line break.
fn strokes(text: &str) -> Vec<Stroke> {
    let mut strokes = vec![];
    let mut units = vec![];
    let mut characters = text.chars().peekable();
    while let Some(character) = characters.next() {
        if matches!(character, '\r' | '\n') {
            if character == '\r' {
                characters.next_if_eq(&'\n');
            }
            if !units.is_empty() {
                strokes.push(Stroke::Text(std::mem::take(&mut units)));
            }
            strokes.push(Stroke::LineBreak);
            continue;
        }
        let mut encoded = [0; 2];
        let encoded = character.encode_utf16(&mut encoded);
        if units.len() + encoded.len() > MAX_UNICODE_UNITS {
            strokes.push(Stroke::Text(std::mem::take(&mut units)));
        }
        units.extend_from_slice(encoded);
    }
    if !units.is_empty() {
        strokes.push(Stroke::Text(units));
    }
    strokes
}

/// Carried in each posted event's source user data, so a tool watching the keyboard,
/// such as `tools/driver/driver.swift`, can tell Lens's paste from a person's keys.
pub const PASTE_MARKER: i64 = 0x4c45_4e53_5056; // "LENSPV"
const EVENT_SOURCE_USER_DATA: u32 = 42; // kCGEventSourceUserData

struct KeyboardEvent(EventRef);

impl KeyboardEvent {
    fn new((key, down, flags): (u16, bool, u64)) -> Result<Self> {
        // SAFETY: a null source selects the default; the event is released on drop.
        let event = unsafe { CGEventCreateKeyboardEvent(ptr::null_mut(), key, down) };
        if event.is_null() {
            return Err("could not create a keyboard event".into());
        }
        // SAFETY: a valid event.
        unsafe {
            CGEventSetFlags(event, flags);
            CGEventSetIntegerValueField(event, EVENT_SOURCE_USER_DATA, PASTE_MARKER);
        }
        Ok(Self(event))
    }

    fn set_text(&self, text: &[u16]) {
        // SAFETY: a valid event; Quartz copies the buffer.
        unsafe { CGEventKeyboardSetUnicodeString(self.0, text.len(), text.as_ptr()) };
    }

    fn post(&self) {
        // SAFETY: a valid event.
        unsafe { CGEventPost(HID_EVENT_TAP, self.0) };
    }
}

impl Drop for KeyboardEvent {
    fn drop(&mut self) {
        // SAFETY: the last owner of the event.
        unsafe { CFRelease(self.0.cast_const()) };
    }
}

#[cfg(test)]
