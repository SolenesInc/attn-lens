//! Pastes text at the cursor of the app in front (D6 on the plan): save the
//! clipboard, write the text, post ⌘V, and put the clipboard back once the paste
//! has landed. Chromium 155 and 156 drop a ⌘V that races their own clipboard
//! notification, so there the text is typed instead.
//!
//! Adapted from Hex's `src/paste.rs` and `src/keyboard.rs`
//! (<https://github.com/anomalyco/hex>, commit 54d1ebf), MIT License, Copyright (c)
//! 2026 Christopher Langton. See THIRD_PARTY_NOTICES.md. Kept: the clipboard
//! snapshot of every item and format, the transient write clipboard managers skip,
//! the restore that stands down when something else wrote the clipboard, the
//! layout-aware ⌘V, and typing for Chromium 155–156. Cut: continuing a previous
//! paste, smart spacing, Labs switches and the input-activity watch they need,
//! since Lens pastes one dictation once.
