#[derive(Clone, Debug, PartialEq, Eq)]
struct Snapshot {
    items: Vec<Vec<Flavor>>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
struct Flavor {
    data_type: String,
    data: Vec<u8>,
    flags: u32,
}

struct Pasteboard(PasteboardRef);

impl Drop for Pasteboard {
    fn drop(&mut self) {
        // SAFETY: we own the reference `PasteboardCreate` returned.
        unsafe { CFRelease(self.0) };
    }
}

fn capture_clipboard(clipboard: &NSPasteboard) -> Result<Snapshot> {
    let pasteboard = create_pasteboard(&clipboard.name())?;
    // SAFETY: a valid pasteboard.
    unsafe { PasteboardSynchronize(pasteboard.0) };
    let mut item_count = 0;
    // SAFETY: as above, with a valid out pointer.
    check(
        unsafe { PasteboardGetItemCount(pasteboard.0, &mut item_count) },
        "count clipboard items",
    )?;
    let mut items = Vec::with_capacity(item_count);
    for index in 1..=item_count {
        let mut item = ptr::null_mut();
        // SAFETY: `index` is within the count just read.
        check(
            unsafe { PasteboardGetItemIdentifier(pasteboard.0, index as isize, &mut item) },
            "identify a clipboard item",
        )?;
        let mut flavors = ptr::null();
        // SAFETY: a valid item; we release the copied array below.
        check(
            unsafe { PasteboardCopyItemFlavors(pasteboard.0, item, &mut flavors) },
            "list clipboard formats",
        )?;
        if flavors.is_null() {
            return Err("could not list clipboard formats".into());
        }
        let result = item_flavors(&pasteboard, item, flavors);
        // SAFETY: we own the copied array.
        unsafe { CFRelease(flavors) };
        items.push(result?);
    }
    Ok(Snapshot { items })
}

fn item_flavors(
    pasteboard: &Pasteboard,
    item: PasteboardItemId,
    flavors: CfArrayRef,
) -> Result<Vec<Flavor>> {
    // SAFETY: a valid array.
    let count = unsafe { CFArrayGetCount(flavors) };
    let mut entries = Vec::with_capacity(count as usize);
    for index in 0..count {
        // SAFETY: `index` is within the array.
        let flavor = unsafe { CFArrayGetValueAtIndex(flavors, index) };
        if flavor.is_null() {
            return Err("a clipboard format was unavailable".into());
        }
        let mut flags = 0;
        // SAFETY: a valid item and flavor, with a valid out pointer.
        check(
            unsafe { PasteboardGetItemFlavorFlags(pasteboard.0, item, flavor, &mut flags) },
            "inspect a clipboard format",
        )?;
        entries.push((flavor, flags));
    }
    // A format the system translated from another is made again from it.
    let authoritative = entries
        .iter()
        .any(|&(_, flags)| flags & SYSTEM_TRANSLATED_FLAVOR == 0);
    let mut kept = vec![];
    for (flavor, flags) in entries {
        if authoritative && flags & SYSTEM_TRANSLATED_FLAVOR != 0 {
            continue;
        }
        let data_type = cf_string(flavor)?;
        let mut data = ptr::null();
        // SAFETY: a valid item and flavor; we release the copied data below.
        let status = unsafe { PasteboardCopyItemFlavorData(pasteboard.0, item, flavor, &mut data) };
        if status == BAD_PASTEBOARD_FLAVOR {
            continue;
        }
        check(status, "save a clipboard format")?;
        if data.is_null() {
            return Err("a clipboard format's data was unavailable".into());
        }
        let bytes = cf_data(data);
        // SAFETY: we own the copied data.
        unsafe { CFRelease(data) };
        kept.push(Flavor {
            data_type,
            data: bytes?,
            flags: flags & 0x0f,
        });
    }
    Ok(kept)
}

/// One item carrying the text and the markers, written at once, so a polling
/// clipboard manager never sees the text without them.
fn write_clipboard_text(clipboard: &NSPasteboard, text: &str) -> Result<()> {
    let item = NSPasteboardItem::new();
    let marker = NSData::new();
    let marked = CLIPBOARD_MANAGER_MARKERS
        .iter()
        .all(|name| item.setData_forType(&marker, &NSString::from_str(name)));
    // SAFETY: an AppKit constant.
    let written =
        item.setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString });
    if !(marked && written) {
        return Err("could not prepare the text for the clipboard".into());
    }
    clipboard.clearContents();
    let items: [Retained<NSPasteboardItem>; 1] = [item];
    let objects = items
        .iter()
        .map(|item| ProtocolObject::from_ref(&**item))
        .collect::<Vec<&ProtocolObject<dyn NSPasteboardWriting>>>();
    clipboard
        .writeObjects(&NSArray::from_slice(&objects))
        .then_some(())
        .ok_or_else(|| "could not write the clipboard".into())
}

fn restore_clipboard(clipboard: &NSPasteboard, snapshot: &Snapshot) -> Result<()> {
    let pasteboard = create_pasteboard(&clipboard.name())?;
    // SAFETY: a valid pasteboard.
    unsafe { PasteboardSynchronize(pasteboard.0) };
    // SAFETY: as above.
    check(
        unsafe { PasteboardClear(pasteboard.0) },
        "clear the clipboard",
    )?;
    for (index, item) in snapshot.items.iter().enumerate() {
        let item_id = (index + 1) as PasteboardItemId;
        for flavor in item {
            let data_type = cf_string_create(&flavor.data_type)?;
            // SAFETY: the slice is valid for its length; CoreFoundation copies it.
            let data = unsafe {
                CFDataCreate(
                    ptr::null(),
                    flavor.data.as_ptr(),
                    flavor.data.len() as isize,
                )
            };
            if data.is_null() {
                // SAFETY: we own `data_type`.
                unsafe { CFRelease(data_type) };
                return Err("could not encode a clipboard format".into());
            }
            // SAFETY: valid pasteboard, string and data; we release both after.
            let status = unsafe {
                PasteboardPutItemFlavor(pasteboard.0, item_id, data_type, data, flavor.flags)
            };
            // SAFETY: we own both.
            unsafe {
                CFRelease(data);
                CFRelease(data_type);
            }
            if status == DUPLICATE_PASTEBOARD_FLAVOR {
                continue;
            }
            check(status, "put back a clipboard format")?;
        }
    }
    Ok(())
}

fn create_pasteboard(name: &NSString) -> Result<Pasteboard> {
    let mut pasteboard = ptr::null();
    // SAFETY: NSString is toll-free bridged to CFString.
    check(
        unsafe { PasteboardCreate((name as *const NSString).cast(), &mut pasteboard) },
        "open the clipboard",
    )?;
    (!pasteboard.is_null())
        .then_some(Pasteboard(pasteboard))
        .ok_or_else(|| "could not open the clipboard".into())
}

fn check(status: i32, action: &str) -> Result<()> {
    (status == 0)
        .then_some(())
        .ok_or_else(|| format!("could not {action} (status {status})"))
}

fn cf_string_create(value: &str) -> Result<CfStringRef> {
    // SAFETY: the bytes are valid UTF-8 for their length.
    let value = unsafe {
        CFStringCreateWithBytes(
            ptr::null(),
            value.as_ptr(),
            value.len() as isize,
            CF_STRING_ENCODING_UTF8,
            0,
        )
    };
    (!value.is_null())
        .then_some(value)
        .ok_or_else(|| "could not encode a clipboard format name".into())
}

fn cf_string(value: CfStringRef) -> Result<String> {
    // SAFETY: a valid CFString.
    let length = unsafe { CFStringGetLength(value) };
    // SAFETY: a plain size query.
    let capacity = unsafe { CFStringGetMaximumSizeForEncoding(length, CF_STRING_ENCODING_UTF8) }
        .saturating_add(1);
    let mut bytes = vec![0u8; capacity as usize];
    // SAFETY: `bytes` holds `capacity` bytes.
    if !unsafe {
        CFStringGetCString(
            value,
            bytes.as_mut_ptr().cast(),
            capacity,
            CF_STRING_ENCODING_UTF8,
        )
    } {
        return Err("could not decode a clipboard format name".into());
    }
    let end = bytes.iter().position(|b| *b == 0).unwrap_or(bytes.len());
    bytes.truncate(end);
    String::from_utf8(bytes).map_err(|e| e.to_string())
}

fn cf_data(value: CfDataRef) -> Result<Vec<u8>> {
    // SAFETY: a valid CFData.
    let length = unsafe { CFDataGetLength(value) };
    if length <= 0 {
        return Ok(vec![]);
    }
    // SAFETY: as above.
    let bytes = unsafe { CFDataGetBytePtr(value) };
    if bytes.is_null() {
        return Err("a clipboard format's data was unavailable".into());
    }
    // SAFETY: CoreFoundation keeps `length` bytes at `bytes` while `value` lives.
    Ok(unsafe { std::slice::from_raw_parts(bytes, length as usize) }.to_vec())
}

// Keys: ⌘V by the key that types V on the current layout, and typed text.

const COMMAND_KEY_CODE: u16 = 55;
const COMMAND_FLAG: u64 = 1 << 20;
const SHIFT_KEY_CODE: u16 = 56;
const SHIFT_FLAG: u64 = 1 << 17;
const RETURN_KEY_CODE: u16 = 36;
